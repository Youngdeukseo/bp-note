/** 약 이름에서 계열을 찾는다. 복합제(예: 텔미사르탄/암로디핀)는 여러 계열이 나온다. */
export function detectClasses(name: string): MedClass[] {
  const n = name.replace(/\s+/g, "");
  return MED_CLASSES.filter((c) => c.names.some((x) => n.includes(x)));
}

export function classesOf(name: string, cls?: string): MedClass[] {
  const found = detectClasses(name);
  if (found.length) return found;
  const manual = MED_CLASSES.find((c) => c.key === cls);
  return manual ? [manual] : [];
}
